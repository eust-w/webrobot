let activeLanguage = readInitialLanguage();

function readInitialLanguage() {
  try {
    const stored = window.localStorage.getItem(STORAGE_KEY);
    if (LANGUAGE_OPTIONS.some((language) => language.code === stored)) return stored;
  } catch {
    // localStorage can be unavailable in restricted browsers.
  }
  return DEFAULT_LANGUAGE;
}

export function getLanguage() {
  return activeLanguage;
}

export function languageMeta(code = activeLanguage) {
  return LANGUAGE_OPTIONS.find((language) => language.code === code) || LANGUAGE_OPTIONS[0];
}

export function setLanguage(code) {
  if (!LANGUAGE_OPTIONS.some((language) => language.code === code)) return activeLanguage;
  activeLanguage = code;
  const meta = languageMeta(code);
  document.documentElement.lang = meta.locale;
  document.documentElement.dir = meta.dir;
  try {
    window.localStorage.setItem(STORAGE_KEY, code);
  } catch {
    // Ignore storage failures; the in-memory language still applies.
  }
  return activeLanguage;
}

export function t(key, params = {}) {
  const table = dictionaries[activeLanguage] || dictionaries[DEFAULT_LANGUAGE];
  const template = table[key] ?? dictionaries[DEFAULT_LANGUAGE][key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name) => params[name] ?? "");
}

